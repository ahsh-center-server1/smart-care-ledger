import { readFileSync, writeFileSync } from 'node:fs';

const source = new URL('../public/domain/fixed-role-policy.js', import.meta.url);
const target = new URL('../functions/fixed-role-policy.cjs', import.meta.url);
const text = readFileSync(source, 'utf8');
if (/^\s*import\s/m.test(text)) throw new Error('Fixed policy must be dependency-free');
const names = [...text.matchAll(/^export (?:const|function) (\w+)/gm)].map(match => match[1]);
const generated = '// Generated by tools/gen-fixed-role-policy.mjs\n'
  + text.replace(/^export /gm, '').trimEnd()
  + `\n\nmodule.exports = { ${names.join(', ')} };\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) throw new Error('Fixed policy server copy is stale');
} else {
  writeFileSync(target, generated);
}
