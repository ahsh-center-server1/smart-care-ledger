// public/domain/trx-totals.js
//
// 「이 거래를 수입/지출 합계에 넣는가」 — 순수 함수. 한 곳에서만 정한다.
//
// 왜 유형이 아니라 표시인가
//   예전에는 유형이 네 개였다: 수입 · 지출 · 자산이동 · 취소. 뒤의 둘은
//   "합계에는 안 들어가지만 잔액에는 들어간다"는 **한 가지 성질**을 말하려고
//   만든 유형이고, 그 대가로
//     · 자산이동은 두 거래를 서로 링크하는 콜러블과 규칙 예외가 필요했고
//     · 화면·집계·보고서 열한 곳이 `type==='자산이동'||type==='취소'` 를 적었다.
//   실제로 두 유형을 쓰는 사람은 많지 않은데 코드는 어디에나 있었다.
//
//   그 성질에 이름을 주면 유형은 다시 둘(수입·지출)로 줄고, 나머지는
//   **체크 한 칸**이 된다.
//
// 구형 기록은 그대로 둔다
//   이미 저장된 자산이동·취소를 고쳐 쓰지 않는다. 결재가 끝난 달의 숫자가
//   배포 때문에 달라지면 안 된다. 그래서 두 유형을 「합계 제외」와 **같은
//   뜻으로 읽는다** — 과거 장부는 손대지 않고도 같은 답이 나온다.
//
// 잔액은 여기서 정하지 않는다
//   이제 **모든 거래**가 잔액에 들어간다(services/balance.js). 취소도
//   마찬가지다 — 취소되면 돈이 실제로 돌아오기 때문이다.

'use strict';

/** 「합계 제외」와 같은 뜻으로 읽는 구형 유형. 새로 만들지는 않는다. */
export const LEGACY_EXCLUDED_TYPES = ['자산이동', '취소'];

/**
 * 수입/지출 합계에 들어가는가.
 *
 * **집계하는 자리는 모두 이것을 써야 한다.** 열한 곳에 같은 조건이 손으로
 * 적혀 있었고, 한 곳만 빠뜨리면 보고서의 합계와 대시보드 카드가 달라진다.
 * 그 차이는 결재가 올라간 뒤에야 눈에 띈다.
 */
export function countsInTotals(trx) {
  if (!trx) return false;
  if (trx.excludeFromTotals === true) return false;
  return !LEGACY_EXCLUDED_TYPES.includes(String(trx.type || ''));
}

/** countsInTotals 의 반대. 화면이 "제외됨" 표시를 붙일 때 읽는다. */
export function isExcludedFromTotals(trx) {
  return !!trx && !countsInTotals(trx);
}
